import uuid
from typing import Dict
from urllib.parse import urlparse

from github import Github
from github.GithubException import GithubException

from backend.config import GITHUB_TOKEN
from backend.models import TestResult

def create_fix_pr(
    repo_url: str,
    diff_files: Dict[str, str],
    summary: str,
    test_before: TestResult,
    test_after: TestResult
) -> str:
    """
    Creates a new branch, commits the files, and opens a PR.
    diff_files: Dict mapping relative file path to its new content.
    """
    if not diff_files:
        raise ValueError("diff_files is empty. No changes to commit.")
    if not test_after.passed:
        raise ValueError("test_after indicates tests are still failing. Cannot open PR.")
        
    if not GITHUB_TOKEN:
        raise ValueError("GITHUB_TOKEN environment variable is not set.")
        
    parsed = urlparse(repo_url)
    path_parts = parsed.path.strip('/').split('/')
    if len(path_parts) < 2:
        raise ValueError(f"Could not parse owner/repo from {repo_url}")
    
    owner, repo_name = path_parts[0], path_parts[1]
    if repo_name.endswith('.git'):
        repo_name = repo_name[:-4]
        
    full_name = f"{owner}/{repo_name}"
    
    gh = Github(GITHUB_TOKEN)
    repo = gh.get_repo(full_name)
    
    if not repo.permissions.push:
        raise RuntimeError(
            f"Your GitHub token does not have push access to {full_name}. "
            "Forking is not yet supported in this MVP. Please test against a repository you have write access to."
        )
        
    short_id = uuid.uuid4().hex[:8]
    branch_name = f"repodoctor/fix-{short_id}"
    default_branch = repo.default_branch
    
    try:
        ref = repo.get_branch(default_branch)
        repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=ref.commit.sha)
    except GithubException as e:
        raise RuntimeError(f"Failed to create branch {branch_name}: {e}")
        
    for filepath, content in diff_files.items():
        try:
            try:
                file_contents = repo.get_contents(filepath, ref=branch_name)
                repo.update_file(
                    path=filepath,
                    message=f"RepoDoctor fix: modify {filepath}",
                    content=content,
                    sha=file_contents.sha,
                    branch=branch_name
                )
            except GithubException as e:
                if e.status == 404:
                    repo.create_file(
                        path=filepath,
                        message=f"RepoDoctor fix: create {filepath}",
                        content=content,
                        branch=branch_name
                    )
                else:
                    raise
        except GithubException as e:
            raise RuntimeError(f"Failed to commit file {filepath}: {e}")
            
    pr_title = "RepoDoctor: fix failing tests"
    
    body = f"## RepoDoctor Automated Fix\n\n"
    body += f"### Summary\n{summary}\n\n"
    body += f"### Files Changed\n"
    for f in diff_files.keys():
        body += f"- `{f}`\n"
        
    body += "\n### Test Results Before\n"
    body += f"```\nExit Code: {test_before.exit_code}\nFailed: {', '.join(test_before.failed_tests)}\n```\n"
    
    body += "\n### Test Results After\n"
    body += f"```\nExit Code: {test_after.exit_code}\nPassed: True\n```\n"
    body += "\n---\n*Generated by RepoDoctor, please review before merging.*"
    
    try:
        pr = repo.create_pull(
            title=pr_title,
            body=body,
            head=branch_name,
            base=default_branch
        )
        return pr.html_url
    except GithubException as e:
        raise RuntimeError(f"Failed to create Pull Request: {e}")
